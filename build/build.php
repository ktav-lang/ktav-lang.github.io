<?php

declare(strict_types=1);

/**
 * Static-site builder for the ktav landing page.
 *
 * Assembles `index.html` from the partials under `build/partials/`, so each
 * section of the page stays a small, focused file that's easy to edit (and
 * easy to keep out of an AI assistant's context window). Run from anywhere:
 *
 *     php build/build.php          # build index.html from partials
 *     php build/build.php --js     # also (re)bundle assets/bundle.js (esbuild)
 *
 * The generated `index.html` is committed for GitHub Pages, but it is a build
 * artifact — never edit it by hand. Edit a partial and rebuild.
 */

$ROOT = dirname(__DIR__);
$PARTIALS = __DIR__ . '/partials';
$ICONS = require __DIR__ . '/data/icons.php';

/** Single-path brand logo by slug (see build/data/icons.php). */
function icon(string $slug): string
{
    return $GLOBALS['ICONS'][$slug] ?? '';
}

/** Per-icon SVG viewBox (most logos use the 24 grid; a few differ). */
function iconVB(string $slug): string
{
    return ['vscode' => '0 0 128 128'][$slug] ?? '0 0 24 24';
}

/**
 * Render a partial (`build/partials/<name>.php`) to a string. Partials may
 * call block() themselves to compose — that's how layout.php pulls in the
 * sections.
 */
function block(string $name): string
{
    $path = $GLOBALS['PARTIALS'] . "/{$name}.php";
    if (!is_file($path)) {
        fwrite(STDERR, "build: missing partial '{$name}' ({$path})\n");
        exit(1);
    }
    ob_start();
    include $path;
    return rtrim((string) ob_get_clean()) . "\n";
}

$html = block('layout');
file_put_contents($ROOT . '/index.html', $html);
printf("✓ built index.html — %d bytes\n", strlen($html));

// Concatenate the CSS partials (ordered by their numeric filename prefix)
// into assets/styles.css.
$cssFiles = glob(__DIR__ . '/styles/*.css');
sort($cssFiles);
$css = "/* GENERATED by build/build.php from build/styles/*.css — do not edit. */\n\n";
foreach ($cssFiles as $f) {
    $css .= file_get_contents($f) . "\n";
}
file_put_contents($ROOT . '/assets/styles.css', $css);
printf("✓ built assets/styles.css — %d bytes from %d partials\n", strlen($css), count($cssFiles));

// Full asset rebuild (`--js`): compile Tailwind → static CSS and bundle the JS.
if (in_array('--js', $argv, true)) {
    chdir($ROOT);

    $tw = 'npx -y tailwindcss@3 -c build/tailwind/tailwind.config.js -i build/tailwind/input.css -o assets/tailwind.css --minify 2>&1';
    echo "→ {$tw}\n";
    exec($tw, $twOut, $twCode);
    echo implode("\n", array_slice($twOut, -2)) . "\n";
    echo $twCode === 0 ? "✓ assets/tailwind.css built\n" : "✗ tailwind failed (code {$twCode}) — run it manually\n";

    $cmd = 'npx --yes esbuild assets/app.js --bundle --format=iife --target=es2020 --outfile=assets/bundle.js 2>&1';
    echo "→ {$cmd}\n";
    exec($cmd, $lines, $code);
    echo implode("\n", $lines) . "\n";
    echo $code === 0 ? "✓ assets/bundle.js rebuilt\n" : "✗ esbuild failed (code {$code}) — run it manually\n";
}
